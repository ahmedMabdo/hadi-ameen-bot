// Generate the machine-derived half of _entity-index.md from _entity-classes.tsv, so the registry and
// the index cannot disagree. Writes between two sentinel comments, leaving the hand-written prose above
// it untouched.

const fs = require('fs');
const path = require('path');

const REPO = process.cwd();
const KG = path.join(REPO, 'docs/knowledge-graph');
const SYS = path.join(KG, '_system');
const TARGET = path.join(SYS, '_entity-index.md');
const BEGIN = '<!-- BEGIN generated: entity registry (gen-entity-index.js) -->';
const END = '<!-- END generated: entity registry -->';
const WRITE = process.argv.includes('--write');

const lines = (t) => String(t).split('\n').map((l) => l.replace(/\r$/, ''));

// entity -> note basename or path, from the note that declares it
function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.md')) out.push(p);
  }
  return out;
}
const notes = walk(KG).map((abs) => {
  const rel = path.relative(KG, abs).split(path.sep).join('/');
  const text = fs.readFileSync(abs, 'utf8');
  const fm = (text.match(/^---\r?\n([\s\S]*?)\r?\n---/) || [])[1] || '';
  return {
    rel,
    base: path.basename(rel, '.md'),
    entity: ((fm.match(/^entity:\s*(.+)$/m) || [])[1] || '').trim(),
    noteType: ((fm.match(/^note_type:\s*(.+)$/m) || [])[1] || '').trim(),
    covers: (((fm.match(/^covers:\s*\[([^\]]*)\]/m) || [])[1]) || '').split(',').map((s) => s.trim()).filter(Boolean),
  };
});
const baseCount = new Map();
for (const n of notes) baseCount.set(n.base, (baseCount.get(n.base) || 0) + 1);
const linkTo = (n) => (baseCount.get(n.base) === 1 ? n.base : n.rel.replace(/\.md$/, ''));

const RANK = { technical: 3, single: 3, business: 2 };
const own = new Map();
for (const n of notes) {
  if (!n.entity) continue;
  const r = RANK[n.noteType] || 1;
  const prev = own.get(n.entity);
  if (!prev || r > prev.r) own.set(n.entity, { link: linkTo(n), r });
}
const host = new Map();
for (const n of notes) for (const c of n.covers) if (!host.has(c)) host.set(c, linkTo(n));

const rows = lines(fs.readFileSync(path.join(SYS, '_entity-classes.tsv'), 'utf8'))
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => l.split('\t'))
  .filter((f) => f.length >= 7);

const esc = (s) => String(s).replace(/\|/g, '\\|');
const documented = rows.filter((r) => /^(pair|single|covered-by:)/.test(r[3]));
const excluded = rows.filter((r) => !/^(pair|single|covered-by:)/.test(r[3]));

const out = [];
out.push(BEGIN);
out.push('');
out.push('## Every classified entity — generated from `_entity-classes.tsv`');
out.push('');
out.push('> Generated by `_system/gen-entity-index.js`; do not edit between the sentinels. The hand-written');
out.push('> sections above carry the judgement, this table carries the completeness. Regenerate after any');
out.push('> change to `_entity-classes.tsv`, and `verify-notes.js` will fail if the two disagree.');
out.push('');
out.push(`**${rows.length} classified entities** — ${documented.length} documented, ${excluded.length} excluded with stated evidence.`);
out.push('');
out.push('### Documented');
out.push('');
out.push('| Entity | Class | Shape | Context | Feature | Note |');
out.push('|---|---|---|---|---|---|');
for (const r of documented.slice().sort((a, b) => a[0].localeCompare(b[0]))) {
  const [entity, , cls, shape, ctx, feat] = r;
  let note = '—';
  if (own.has(entity)) note = `[[${own.get(entity).link}\\|${entity}]]`;
  else if (shape.startsWith('covered-by:')) {
    const h = shape.slice('covered-by:'.length);
    note = host.has(entity) ? `folded into [[${host.get(entity)}\\|${h}]]` : `folded into ${esc(h)}`;
  }
  out.push(`| \`${entity}\` | ${esc(cls)} | ${esc(shape.split(':')[0])} | ${esc(ctx)} | ${esc(feat)} | ${note} |`);
}
out.push('');
out.push('### Excluded, with the evidence for each exclusion');
out.push('');
out.push('| Entity | Class | Why it is not documented |');
out.push('|---|---|---|');
for (const r of excluded.slice().sort((a, b) => a[0].localeCompare(b[0]))) {
  out.push(`| \`${r[0]}\` | ${esc(r[2])} | ${esc(r[6]).slice(0, 400)} |`);
}
out.push('');
out.push(END);

const body = fs.readFileSync(TARGET, 'utf8');
let next;
if (body.includes(BEGIN)) {
  next = body.replace(new RegExp(BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')), out.join('\n'));
} else {
  next = body.replace(/\s*$/, '') + '\n\n---\n\n' + out.join('\n') + '\n';
}
if (WRITE) fs.writeFileSync(TARGET, next, 'utf8');
console.log(`${documented.length} documented + ${excluded.length} excluded = ${rows.length} rows ${WRITE ? 'written' : 'to write'}`);
console.log(`entities with a note of their own: ${[...own.keys()].length}`);

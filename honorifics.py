#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""حارس الألقاب (Honorifics Guard) — نقطة 1 (قرار آسر).

المشكلة:
  التعليمات في HADI_PERSONA.md / CLAUDE.md بتقول ناديّ الأونرز بـ«باشمهندس»
  دايمًا، لكن الموديل بيزل أحيانًا ويكتب «أحمد عبده» / «محمود عبده» من غير لقب.

الحل:
  حارس حتمي (صفري الاعتماد على طاعة الموديل) بيتطبّق على **أي نص خارج من هادي**
  قبل الإرسال — بيتأكد إن الأسماء الكاملة للأونرز مسبوقة بـ«باشمهندس».

النطاق (متحفّظ عمدًا — صفر false positives):
  - بيصحّح الاسم الكامل بس: «أحمد عبده» / «محمود عبده» / «محمد عبده».
    دي أسماء الأونرز الفريدة (اللقب عبده مقترن بالأسماء دي = أونر) — «ياسمين عبده»
    (تيستر) أو «أحمد محمود» (تيم ليد) مابيتلمسوش.
  - الأسماء الأولى المجرّدة (أحمد/محمود/محمد لوحدها) **مابتتلمسش** — بتتلخبط مع
    أعضاء تانيين كتير في الفريق، والتعليمات في الشخصية بتغطّيها.

بيحترم الألقاب الموجودة: لو الاسم مسبوق بـ«باشمهندس» أو «مهندس» أو «م.» → يسيبه.
"""
import re

# الأسماء الكاملة للأونرز — لازم «باشمهندس» قبلها دايمًا (قرار آسر)
OWNER_FULL_NAMES = ("أحمد عبده", "محمود عبده", "محمد عبده")

# ألقاب لو موجودة قبل الاسم يبقى مصحّح خلاص — بلاش تكرار
_TITLE_HINTS = ("باشمهندس", "مهندس", "م.")

TITLE = "باشمهندس"

# حرف عربي — عشان نمنع مطابقة جزء من كلمة أكبر
_AR = r"[؀-ۿ]"


def _already_titled(text: str, start: int) -> bool:
    """هل الاسم اللي بادئ عند start مسبوق بلقب فعلاً؟"""
    prev = text[max(0, start - 14):start]
    return any(h in prev for h in _TITLE_HINTS)


def enforce(text: str) -> str:
    """يرجّع النص بعد ما يتأكد إن أسماء الأونرز الكاملة مسبوقة بـ«باشمهندس».

    آمن للاستدعاء على أي مخرج (رد، ملخص، تنبيه، تعليق تذكرة). idempotent —
    تشغيله مرتين مايضّرش."""
    if not text:
        return text
    for name in OWNER_FULL_NAMES:
        rx = re.compile(r"(?<!" + _AR + r")" + re.escape(name) + r"(?!" + _AR + r")")

        def _repl(m):
            if _already_titled(m.string, m.start()):
                return m.group(0)
            return f"{TITLE} {m.group(0)}"

        text = rx.sub(_repl, text)
    return text


def _selftest() -> None:
    cases = [
        # (input, expected)
        ("راجع مع أحمد عبده النقطة دي", "راجع مع باشمهندس أحمد عبده النقطة دي"),
        ("محمود عبده وافق على الريليز", "باشمهندس محمود عبده وافق على الريليز"),
        ("يا محمود عبده محتاجين تأكيدك", "يا باشمهندس محمود عبده محتاجين تأكيدك"),
        # موجود اللقب خلاص — مايتكررش
        ("باشمهندس أحمد عبده قال تمام", "باشمهندس أحمد عبده قال تمام"),
        ("مهندس محمود عبده", "مهندس محمود عبده"),
        # مايتلمسش الأسماء التانية اللي لقبها عبده أو أسماء أولى مجردة
        ("ياسمين عبده رفعت التذكرة", "ياسمين عبده رفعت التذكرة"),
        ("أحمد محمود شغال على الباك اند", "أحمد محمود شغال على الباك اند"),
        ("كلمت أحمد في الموضوع", "كلمت أحمد في الموضوع"),
        # الاسم المجرّد للأونر مايتلمسش (تغطيه التعليمات مش الحارس)
        ("محمود قال كذا", "محمود قال كذا"),
    ]
    ok = True
    for src, want in cases:
        got = enforce(src)
        flag = "PASS" if got == want else "FAIL"
        if got != want:
            ok = False
        print(f"{flag}: {src!r} -> {got!r}")
    print("SELFTEST", "PASS — حارس الألقاب سليم" if ok else "FAIL")


if __name__ == "__main__":
    _selftest()
